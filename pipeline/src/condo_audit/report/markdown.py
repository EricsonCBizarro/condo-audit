"""Markdown audit report for one condominium, straight from the database."""

from __future__ import annotations

from decimal import Decimal

from condo_audit.db import Database
from condo_audit.formatting import brl

SEVERITY_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3}
SEVERITY_BADGE = {"critical": "🟥 critical", "high": "🟧 high", "medium": "🟨 medium", "low": "⬜ low"}


def render(db: Database, slug: str) -> str:
    with db.transaction() as conn:
        condo = conn.execute("select id, name, city from condominiums where slug = %s", (slug,)).fetchone()
        if condo is None:
            raise LookupError(f"condominium '{slug}' not found")
        docs = conn.execute(
            "select id, title, type, page_count, text_source from documents where condominium_id = %s",
            (condo["id"],),
        ).fetchall()
        findings = conn.execute(
            "select * from findings where condominium_id = %s and is_active order by id", (condo["id"],)
        ).fetchall()

    titles = {d["id"]: d["title"] for d in docs}
    findings.sort(key=lambda f: (SEVERITY_ORDER.get(f["severity"], 9), f["period"] or "", f["rule_code"]))
    irregular = [f for f in findings if f["category"] == "irregularity"]
    review = [f for f in findings if f["category"] != "irregularity"]
    at_stake = sum((f["amount"] or Decimal(0) for f in irregular), Decimal(0))
    pages = sum(d["page_count"] or 0 for d in docs)
    ocr_docs = sum(1 for d in docs if d["text_source"] in {"ocr", "mixed"})

    out = [
        f"# Audit report — {condo['name']}",
        "",
        "> Generated by condo-audit from **synthetic, fictional data**.",
        "",
        "| Documents | Pages | Read by OCR | Irregularities | Review items | Amount involved |",
        "|---:|---:|---:|---:|---:|---:|",
        f"| {len(docs)} | {pages} | {ocr_docs} documents | {len(irregular)} | {len(review)} | R$ {brl(at_stake)} |",
        "",
        "## Findings",
        "",
        "| Severity | Rule | Period | Finding | Amount (R$) |",
        "|---|---|---|---|---:|",
    ]
    for f in irregular:
        amount = brl(f["amount"]) if f["amount"] is not None else "—"
        out.append(
            f"| {SEVERITY_BADGE.get(f['severity'], f['severity'])} | `{f['rule_code']}` | {f['period'] or '—'} "
            f"| {f['title']} | {amount} |"
        )
    out += ["", "## Details and evidence", ""]
    for i, f in enumerate(irregular + review, start=1):
        out += [f"### {i}. {f['title']}", "", f["explanation"], ""]
        for ev in f["evidence"]:
            source = titles.get(ev["document_id"], f"document {ev['document_id']}")
            out.append(f"- **{ev['label']}** — {source}, page {ev['page']}: `{ev['excerpt']}`")
        out.append("")
    return "\n".join(out).rstrip() + "\n"
